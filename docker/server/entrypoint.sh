#!/bin/bash
#
# Core3 container entrypoint.
#
#   1. checks the TRE files mounted at /tre
#   2. waits for the database and points the galaxy row at GALAXY_ADDRESS
#   3. writes conf/config-local.lua from the environment
#   4. runs core3 with its console on a FIFO, so `./swgemu console` / `./swgemu cmd`
#      can talk to it and `docker stop` triggers a clean "exit" (saves the world)
#      instead of killing the process mid-write.

set -euo pipefail

BIN_DIR=/opt/core3/bin
CONSOLE_FIFO=/tmp/core3-console
CONFIG_DIR=/opt/core3/config.d

: "${DB_HOST:=db}"
: "${DB_PORT:=3306}"
: "${DB_NAME:=swgemu}"
: "${DB_USER:=swgemu}"
: "${DB_PASS:?DB_PASS must be set}"
: "${DB_SECRET:?DB_SECRET must be set}"
: "${GALAXY_ID:=2}"
: "${GALAXY_NAME:=Core3}"
: "${GALAXY_ADDRESS:=127.0.0.1}"
: "${CORE3_ADMINS:=}"
: "${CORE3_GDB:=1}"
: "${LOG_LEVEL:=4}"

msg() { echo -e "\033[1;32m[core3-entrypoint]\033[0m $*"; }
die() { echo -e "\033[1;31m[core3-entrypoint] ERROR:\033[0m $*" >&2; exit 1; }

lua_str() {
    local s=${1//\\/\\\\}
    printf '"%s"' "${s//\"/\\\"}"
}

sql_str() {
    local s=${1//\\/\\\\}
    printf "'%s'" "${s//\'/\'\'}"
}

db() {
    MYSQL_PWD="${DB_PASS}" mariadb --protocol=tcp -h "${DB_HOST}" -P "${DB_PORT}" -u "${DB_USER}" "${DB_NAME}" "$@"
}

cd "${BIN_DIR}"

# --- 1. TRE files -----------------------------------------------------------
mapfile -t tre_files < <(sed -n '/TreFiles = {/,/}/p' conf/config.lua | grep -o '"[^"]*\.tre"' | tr -d '"')
missing=()
for f in "${tre_files[@]}"; do
    [ -s "/tre/${f}" ] || missing+=("${f}")
done
if [ ${#missing[@]} -gt 0 ]; then
    die "${#missing[@]} of ${#tre_files[@]} TRE files are missing from /tre (first: ${missing[0]}). Run ./swgemu tre on the host."
fi
msg "Found all ${#tre_files[@]} TRE files."

# --- 2. Database ------------------------------------------------------------
msg "Waiting for database ${DB_HOST}:${DB_PORT}..."
for _ in $(seq 1 90); do
    if db -e 'SELECT 1 FROM galaxy LIMIT 1' >/dev/null 2>&1; then
        break
    fi
    sleep 2
done
db -e 'SELECT 1 FROM galaxy LIMIT 1' >/dev/null || die "Database is not reachable or the swgemu schema was not loaded."

db -e "UPDATE galaxy SET name = $(sql_str "${GALAXY_NAME}"), address = $(sql_str "${GALAXY_ADDRESS}"), port = 44463, pingport = 44462 WHERE galaxy_id = ${GALAXY_ID};"
msg "Galaxy '${GALAXY_NAME}' (id ${GALAXY_ID}) advertised at ${GALAXY_ADDRESS}."

if [ -n "${CORE3_ADMINS}" ]; then
    in_list=""
    IFS=', ' read -r -a admins <<< "${CORE3_ADMINS}"
    for a in "${admins[@]}"; do
        [ -n "${a}" ] && in_list+="${in_list:+,}$(sql_str "${a}")"
    done
    if [ -n "${in_list}" ]; then
        db -e "UPDATE accounts SET admin_level = 15 WHERE username IN (${in_list});"
        msg "Admin level 15 applied to existing accounts: ${CORE3_ADMINS}"
    fi
fi

# --- 3. config-local.lua ----------------------------------------------------
{
    echo "-- Generated by core3-entrypoint at $(date -u '+%Y-%m-%d %H:%M:%S UTC'). Do not edit:"
    echo "-- it is rewritten on every start. Put overrides in server-config/*.lua instead."
    echo "DBHost = $(lua_str "${DB_HOST}")"
    echo "DBPort = ${DB_PORT}"
    echo "DBName = $(lua_str "${DB_NAME}")"
    echo "DBUser = $(lua_str "${DB_USER}")"
    echo "DBPass = $(lua_str "${DB_PASS}")"
    echo "DBSecret = $(lua_str "${DB_SECRET}")"
    echo "MantisHost = \"\" -- disabled"
    echo "ZoneGalaxyID = ${GALAXY_ID}"
    echo "TrePath = \"/tre\""
    echo "LogFileLevel = ${LOG_LEVEL}"
    echo "ProgressMonitors = \"false\""
    for extra in "${CONFIG_DIR}"/*.lua; do
        [ -f "${extra}" ] || continue
        echo
        echo "-- >>> ${extra##*/}"
        cat "${extra}"
    done
} > conf/config-local.lua
msg "Wrote conf/config-local.lua"

# --- 4. Run core3 -----------------------------------------------------------
rm -f "${CONSOLE_FIFO}"
mkfifo "${CONSOLE_FIFO}"
# Hold the FIFO open read-write so core3 never sees EOF on its console.
exec 3<>"${CONSOLE_FIFO}"

# Forward an attached terminal (./swgemu console) into the console FIFO.
# Background jobs get /dev/null as stdin, so hand cat a saved copy of it.
if [ -t 0 ]; then
    exec 4<&0
    cat <&4 >&3 &
fi

if [ "${CORE3_GDB}" = "1" ]; then
    # Run under gdb so a crash leaves a full backtrace in `./swgemu logs`.
    cat > /tmp/core3.gdb <<'EOF'
set pagination off
set confirm off
set disable-randomization off
set print thread-events off
set print inferior-events off
handle SIGPIPE nostop noprint pass
handle SIGUSR1 nostop noprint pass
run
if $_isvoid($_exitcode)
  echo \n*** core3 crashed, backtraces follow ***\n
  bt
  thread apply all bt
  kill
  quit 134
else
  quit $_exitcode
end
EOF
    cmd=(gdb -q -batch -x /tmp/core3.gdb --args ./core3 "$@")
else
    cmd=(./core3 "$@")
fi

# setsid: a Ctrl-C on an attached terminal must not reach core3 directly.
setsid "${cmd[@]}" <&3 &
core_pid=$!

shutting_down=false
graceful_exit() {
    if ! ${shutting_down}; then
        shutting_down=true
        msg "Stop requested, sending 'exit' to the console (saving world, this can take a minute)..."
        echo "exit" >&3
    fi
}
trap graceful_exit TERM INT

msg "core3 started (pid ${core_pid}). Waiting for zones to load; 'READY' appears when the console is up."

# wait returns early when a trap fires; keep waiting until core3 is really gone.
while :; do
    status=0
    wait "${core_pid}" || status=$?
    kill -0 "${core_pid}" 2>/dev/null || break
done

msg "core3 exited with status ${status}."
exit "${status}"
